'use client';

import { Award, BadgePercent, Headset, ShieldCheck, Share2, Network, TrendingUp, Wallet } from 'lucide-react';
import { useCommerceStore } from '@/stores/useCommerceStore';
import { RANK_PROGRESSION_RULES, getNextRankProgress } from '@/types/hellobee';
import { formatPrice } from '@/lib/utils';

const MEMBER_BENEFITS = [
  {
    icon: ShieldCheck,
    title: '5-Year Factory Warranty',
    text: 'Every original Enagic ionizer ships with full manufacturer coverage for parts and service.',
  },
  {
    icon: Headset,
    title: 'Dedicated Hydration Specialist',
    text: 'Your assigned specialist guides setup, water settings, and filter replacement schedules.',
  },
  {
    icon: Share2,
    title: 'Personal Referral Code',
    text: 'Share your code with friends and family so their purchases are linked to your network.',
  },
  {
    icon: BadgePercent,
    title: 'Member Offers',
    text: 'Early access to promotions on filters, parts, and accessories for registered members.',
  },
];

const EMPLOYEE_BENEFITS = [
  {
    icon: BadgePercent,
    title: '10% Direct Commission',
    text: 'Earn 10% on every valid order placed with your sponsor code.',
  },
  {
    icon: Network,
    title: '1% Owner Override',
    text: 'Owners earn a 1% override on orders generated by employees in their network.',
  },
  {
    icon: TrendingUp,
    title: 'Rank Progression 1A to 5A',
    text: 'Advance through ranks as your valid orders grow. Each rank unlocks the next tier of the network.',
  },
  {
    icon: Wallet,
    title: 'Payout Requests',
    text: 'Request a payout of your available balance to your bank account from the employee portal.',
  },
];

function BenefitCard({ icon: Icon, title, text }: { icon: typeof Award; title: string; text: string }) {
  return (
    <div className="bg-white border border-[#E5E5E5] rounded-lg p-5 flex gap-4">
      <div className="w-10 h-10 shrink-0 rounded-full bg-[#F5F4F0] flex items-center justify-center">
        <Icon className="w-5 h-5 text-[#111111]" />
      </div>
      <div>
        <h3 className="text-sm font-semibold text-[#111111]">{title}</h3>
        <p className="text-xs text-[#666666] leading-relaxed mt-1">{text}</p>
      </div>
    </div>
  );
}

export function BenefitsTab() {
  const currentUser = useCommerceStore((s) => s.currentUser);
  const members = useCommerceStore((s) => s.hellobeeMembers);
  const currency = useCommerceStore((s) => s.currency);

  if (!currentUser) return null;

  const isEmployee = currentUser.role === 'employee';
  const member = members.find((m) => m.email.toLowerCase() === currentUser.email.toLowerCase());
  const progress = member ? getNextRankProgress(member.rank, member.validOrdersCount) : null;

  return (
    <div className="space-y-8">
      <section>
        <h2 className="text-xs uppercase tracking-wider font-bold text-[#111111] mb-4">Member Benefits</h2>
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          {MEMBER_BENEFITS.map((b) => (
            <BenefitCard key={b.title} {...b} />
          ))}
        </div>
      </section>

      {isEmployee && (
        <section>
          <h2 className="text-xs uppercase tracking-wider font-bold text-[#111111] mb-4">Employee Benefits</h2>

          {member && progress && (
            <div className="bg-[#111111] text-white rounded-lg p-6 mb-4">
              <div className="flex flex-wrap items-center justify-between gap-3">
                <div className="flex items-center gap-2">
                  <Award className="w-5 h-5 text-[#B9A58B]" />
                  <span className="text-sm font-semibold">Current rank: {member.rank}</span>
                </div>
                <div className="text-xs text-white/70">
                  Available balance{' '}
                  <span className="text-white font-semibold">{formatPrice(member.availableBalance, currency)}</span>
                </div>
              </div>
              <div className="mt-4">
                <div className="flex justify-between text-[11px] text-white/70 mb-1.5">
                  <span>
                    {progress.nextRank === 'MAX'
                      ? 'Top rank reached'
                      : `${progress.current} / ${progress.required} valid orders to ${progress.nextRank}`}
                  </span>
                  <span>{progress.percent}%</span>
                </div>
                <div className="h-2 rounded-full bg-white/15 overflow-hidden">
                  <div className="h-full bg-[#B9A58B] transition-all" style={{ width: `${progress.percent}%` }} />
                </div>
              </div>
            </div>
          )}

          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            {EMPLOYEE_BENEFITS.map((b) => (
              <BenefitCard key={b.title} {...b} />
            ))}
          </div>

          <div className="mt-4 bg-white border border-[#E5E5E5] rounded-lg overflow-x-auto">
            <table className="w-full text-xs">
              <thead className="bg-[#F5F4F0] text-[#555555] uppercase tracking-wider">
                <tr>
                  <th className="text-left px-4 py-2.5 font-semibold">Rank</th>
                  <th className="text-left px-4 py-2.5 font-semibold">Valid orders to advance</th>
                  <th className="text-left px-4 py-2.5 font-semibold">Next rank</th>
                </tr>
              </thead>
              <tbody>
                {RANK_PROGRESSION_RULES.map((r) => (
                  <tr
                    key={r.currentRank}
                    className={`border-t border-[#EEEEEE] ${member?.rank === r.currentRank ? 'bg-[#FBF8F2] font-semibold' : ''}`}
                  >
                    <td className="px-4 py-2.5">{r.currentRank}</td>
                    <td className="px-4 py-2.5">{r.requiredOrders}</td>
                    <td className="px-4 py-2.5">{r.nextRank}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </section>
      )}
    </div>
  );
}
